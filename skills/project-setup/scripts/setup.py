#!/usr/bin/env python3
"""project-setup: write and check a repository's Claude Code project files.

    setup.py detect <repo>             what the repository already has, as JSON (reads only)
    setup.py render <repo> [--dry-run] write the files from <repo>/.claude/project-setup.json
    setup.py check  <repo>             report drift and mistakes (reads only; exit 1 on a finding)

Standard library only. Every file this script owns ends with the marker line below; files it
creates once (decision log, the owner's own rules, the PR template) are never changed again.
"""
from __future__ import annotations

import argparse
import difflib
import json
import re
import subprocess
import sys
from pathlib import Path

CONFIG = ".claude/project-setup.json"
TEMPLATES = Path(__file__).resolve().parent.parent / "templates"
MARK = "generated by project-setup; change .claude/project-setup.json and render again"
BLOCK_START = "<!-- project-setup:start -->"
BLOCK_END = "<!-- project-setup:end -->"

SIZES = ("solo", "open-source")
AUTONOMY = ("supervised", "guided", "autonomous")
# What `economy` decides. Each value can be overridden by the config key of the same name.
ECONOMY = {
    "frugal": {"worker_model": "sonnet", "reviewer_model": "sonnet", "review_rounds": 1,
               "critical_review_rounds": 2, "parallel_workers": 1, "plan_first": "critical"},
    "balanced": {"worker_model": "sonnet", "reviewer_model": "opus", "review_rounds": 2,
                 "critical_review_rounds": 3, "parallel_workers": 2, "plan_first": "critical"},
    "thorough": {"worker_model": "inherit", "reviewer_model": "inherit", "review_rounds": 2,
                 "critical_review_rounds": 4, "parallel_workers": 3, "plan_first": "always"},
}
DEFAULTS = {
    "name": "",
    "size": "solo",
    "autonomy": "guided",
    "economy": "balanced",
    "default_branch": "main",
    "checks": "",
    "critical_paths": [".github/workflows/**", ".claude/**", "CLAUDE.md"],
    "lanes": {},
    "licence_gate": None,      # None: on for open-source, off for solo
    "refused_licences": ["AGPL", "SSPL", "non-commercial or research-only", "no licence stated"],
    "contributing": None,      # None: on for open-source, off for solo
    "label_workflow": None,    # None: on for open-source, off for solo
}
MANIFESTS = ["pyproject.toml", "requirements*.txt", "uv.lock", "package.json", "Cargo.toml",
             "go.mod", "Gemfile", "pom.xml", "build.gradle*", "THIRD_PARTY_LICENSES.md"]
DENY = ["Bash(git push --force*)", "Bash(git push -f *)", "Bash(git push * --force*)"]
ASK_MERGE = ["Bash(gh pr merge*)", "mcp__github__merge_pull_request"]
LABELER_SHA = "8558fd74291d67161a8a78ce36a881fa63b766a9"  # actions/labeler v5.0.0 (MIT)


class ConfigError(Exception):
    pass


# ---------------------------------------------------------------- config

def load_config(repo: Path) -> dict:
    path = repo / CONFIG
    if not path.exists():
        raise ConfigError(f"{CONFIG} not found; write it first (keys: {', '.join(DEFAULTS)})")
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        raise ConfigError(f"{CONFIG} is not valid JSON: {e}") from e
    return normalise(raw)


def normalise(raw: dict) -> dict:
    """Check every key and type, fill defaults, and add the values `economy` and `size` decide."""
    if not isinstance(raw, dict):
        raise ConfigError("the config must be a JSON object")
    overrides = set(ECONOMY["balanced"])
    unknown = set(raw) - set(DEFAULTS) - overrides
    if unknown:
        raise ConfigError(f"unknown key(s): {', '.join(sorted(unknown))}")
    cfg = {**DEFAULTS, **raw}

    def choice(key, allowed):
        if cfg[key] not in allowed:
            raise ConfigError(f"{key} must be one of {', '.join(allowed)}; got {cfg[key]!r}")

    choice("size", SIZES)
    choice("autonomy", AUTONOMY)
    choice("economy", tuple(ECONOMY))
    for key in ("name", "default_branch", "checks"):
        if not isinstance(cfg[key], str) or "\n" in cfg[key]:
            raise ConfigError(f"{key} must be one line of text")
    if not cfg["name"].strip():
        raise ConfigError("name is required")
    for key in ("critical_paths", "refused_licences"):
        if not isinstance(cfg[key], list) or not all(isinstance(v, str) and v for v in cfg[key]):
            raise ConfigError(f"{key} must be a list of non-empty strings")
    if not isinstance(cfg["lanes"], dict):
        raise ConfigError('lanes must be an object: {"<lane>": ["<glob>", ...]}')
    for lane, globs in cfg["lanes"].items():
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", lane):
            raise ConfigError(f"lane name {lane!r}: lower-case letters, digits and hyphens only")
        if not isinstance(globs, list) or not globs or not all(isinstance(g, str) and g for g in globs):
            raise ConfigError(f"lane {lane!r} needs a list of globs")
    for g in cfg["critical_paths"] + [g for gs in cfg["lanes"].values() for g in gs]:
        if re.search(r"""['"\n\\]""", g) or g.startswith("/"):
            raise ConfigError(f"glob {g!r}: relative to the repository root, without quotes or backslashes")
    public = cfg["size"] == "open-source"
    for key in ("licence_gate", "contributing", "label_workflow"):
        if cfg[key] is None:
            cfg[key] = public
        elif not isinstance(cfg[key], bool):
            raise ConfigError(f"{key} must be true or false")
    preset = ECONOMY[cfg["economy"]]
    for key, default in preset.items():
        value = cfg.setdefault(key, default)
        if isinstance(default, int) and (not isinstance(value, int) or isinstance(value, bool) or value < 1):
            raise ConfigError(f"{key} must be a whole number of 1 or more")
        if isinstance(default, str) and (not isinstance(value, str) or not value):
            raise ConfigError(f"{key} must be text")
    if cfg["plan_first"] not in ("critical", "always"):
        raise ConfigError("plan_first must be critical or always")
    if cfg["critical_review_rounds"] < cfg["review_rounds"]:
        raise ConfigError("critical_review_rounds must not be lower than review_rounds")
    return cfg


# ---------------------------------------------------------------- templates

_TAG = re.compile(r"\{\{#(if|unless) (\w+)\}\}((?:(?!\{\{#).)*?)\{\{/\1\}\}", re.S)
_TAG_LINE = re.compile(r"^(\{\{[#/][^}]*\}\})\n", re.M)  # a tag alone on a line leaves no empty line


def fill(text: str, ctx: dict) -> str:
    """{{key}} is replaced; {{#if key}}...{{/if}} and {{#unless key}}...{{/unless}} keep or drop a block."""
    text = _TAG_LINE.sub(r"\1", text)
    while True:
        text, n = _TAG.subn(lambda m: m.group(3) if bool(ctx[m.group(2)]) == (m.group(1) == "if") else "", text)
        if not n:
            break
    return re.sub(r"\{\{(\w+)\}\}", lambda m: str(ctx[m.group(1)]), text)


def context(cfg: dict) -> dict:
    code = lambda items: ", ".join(f"`{i}`" for i in items)  # noqa: E731
    yaml_list = lambda items: "\n".join(f'  - "{i}"' for i in items)  # noqa: E731
    lanes = cfg["lanes"]
    return {
        **cfg,
        "mark": MARK,
        "public": cfg["size"] == "open-source",
        "supervised": cfg["autonomy"] == "supervised",
        "guided": cfg["autonomy"] == "guided",
        "autonomous": cfg["autonomy"] == "autonomous",
        # an owner who approves every plan has to see one for every issue
        "plan_always": cfg["plan_first"] == "always" or cfg["autonomy"] == "supervised",
        "has_checks": bool(cfg["checks"]),
        "has_lanes": bool(lanes),
        "one_worker": cfg["parallel_workers"] == 1,
        "critical_list": code(cfg["critical_paths"]),
        "critical_yaml": yaml_list(cfg["critical_paths"]),
        "manifests_yaml": yaml_list(MANIFESTS),
        "refused_list": ", ".join(cfg["refused_licences"]),
        "lanes_table": "\n".join(f"| `lane:{n}` | {code(g)} |" for n, g in lanes.items()),
    }


def labeler_config(cfg: dict) -> str:
    def rule(label, globs):
        quoted = ", ".join(f"'{g}'" for g in globs)
        return f"'{label}':\n  - changed-files:\n      - any-glob-to-any-file: [{quoted}]\n"
    rules = [rule("critical", cfg["critical_paths"])]
    rules += [rule(f"lane:{n}", g) for n, g in cfg["lanes"].items()]
    return f"# {MARK}\n" + "".join(rules)


# ---------------------------------------------------------------- what render produces

def desired(repo: Path, cfg: dict) -> dict[str, str | None]:
    """Path -> wanted content. None means: remove the file if this script generated it."""
    ctx = context(cfg)
    tpl = lambda name: fill((TEMPLATES / name).read_text(encoding="utf-8"), ctx)  # noqa: E731
    read = lambda rel: (repo / rel).read_text(encoding="utf-8") if (repo / rel).exists() else None  # noqa: E731
    out: dict[str, str | None] = {
        ".claude/agents/lead.md": tpl("agents/lead.md"),
        ".claude/agents/worker.md": tpl("agents/worker.md"),
        ".claude/agents/reviewer.md": tpl("agents/reviewer.md"),
        ".claude/rules/critical.md": tpl("rules/critical.md"),
        ".claude/skills/specify/SKILL.md": tpl("skills/specify/SKILL.md"),
        ".claude/rules/licences.md": tpl("rules/licences.md") if cfg["licence_gate"] else None,
        ".github/labeler.yml": labeler_config(cfg) if cfg["label_workflow"] else None,
        ".github/workflows/labels.yml": (
            fill((TEMPLATES / "github/labels-workflow.yml").read_text(encoding="utf-8"),
                 {**ctx, "labeler_sha": LABELER_SHA}) if cfg["label_workflow"] else None),
        "CLAUDE.md": put_block(read("CLAUDE.md"), tpl("claude-md.md")),
        ".claude/settings.json": merge_settings(read(".claude/settings.json"), cfg),
    }
    contributing = read("CONTRIBUTING.md")
    if cfg["contributing"]:
        out["CONTRIBUTING.md"] = put_block(contributing, tpl("contributing.md"))
    elif contributing and BLOCK_START in contributing:
        out["CONTRIBUTING.md"] = put_block(contributing, "").strip() and put_block(contributing, "") or None
    # Created once, then the project's own: never compared or overwritten.
    for rel, name in (("docs/decisions.md", "project/decisions.md"),
                      (".claude/rules/project.md", "project/rules.md"),
                      (".github/pull_request_template.md", "github/pull_request_template.md")):
        if read(rel) is None:
            out[rel] = tpl(name)
    return out


def put_block(existing: str | None, block: str) -> str:
    """Replace the marked block in a file the project also edits by hand; append it if there is none."""
    block = f"{BLOCK_START}\n{block.strip()}\n{BLOCK_END}\n" if block.strip() else ""
    if not existing:
        return block
    if BLOCK_START in existing and BLOCK_END in existing:
        head, rest = existing.split(BLOCK_START, 1)
        tail = rest.split(BLOCK_END, 1)[1].lstrip("\n")
        return head + block + tail
    return existing.rstrip("\n") + "\n\n" + block


def merge_settings(existing: str | None, cfg: dict) -> str:
    """Add this script's permission rules to .claude/settings.json and leave everything else alone."""
    try:
        settings = json.loads(existing) if existing else {}
    except json.JSONDecodeError as e:
        raise ConfigError(f".claude/settings.json is not valid JSON: {e}") from e
    perms = settings.setdefault("permissions", {})
    ours = set(DENY + ASK_MERGE)
    want = {"deny": DENY, "ask": ASK_MERGE if cfg["autonomy"] == "supervised" else []}
    for key, rules in want.items():
        kept = [r for r in perms.get(key, []) if r not in ours]
        if kept or rules:
            perms[key] = kept + rules
        else:
            perms.pop(key, None)
    return json.dumps(settings, indent=2) + "\n"


def changes(repo: Path, cfg: dict) -> list[tuple[str, str | None, str | None]]:
    """(path, content on disk, wanted content) for every file render would write or remove."""
    result = []
    for rel, new in desired(repo, cfg).items():
        path = repo / rel
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if new is None and (old is None or MARK not in old):
            continue  # nothing to remove, or the file is not ours
        if old != new:
            result.append((rel, old, new))
    return result


# ---------------------------------------------------------------- commands

def cmd_render(repo: Path, dry_run: bool) -> int:
    cfg = load_config(repo)
    todo = changes(repo, cfg)
    if not todo:
        print("Nothing to change: the files match the config.")
    for rel, old, new in todo:
        if dry_run:
            diff = difflib.unified_diff((old or "").splitlines(), (new or "").splitlines(),
                                        f"a/{rel}" if old is not None else "/dev/null",
                                        f"b/{rel}" if new is not None else "/dev/null", lineterm="")
            print("\n".join(diff))
        elif new is None:
            (repo / rel).unlink()
            print(f"removed  {rel}")
        else:
            (repo / rel).parent.mkdir(parents=True, exist_ok=True)
            (repo / rel).write_text(new, encoding="utf-8")
            print(f"{'wrote  ' if old is None else 'updated'}  {rel}")
    if dry_run:
        print(f"\nDry run: {len(todo)} file(s) would change; nothing was written.")
        return 0
    print("\nBy hand, once (the files above only ask; GitHub enforces):")
    print(f"  Protect `{cfg['default_branch']}` on GitHub: require a pull request"
          + (" and passing checks" if cfg["checks"] else "") + ", block force pushes.")
    for line in findings(repo, cfg):
        print(f"  note: {line}")
    return 0


def cmd_check(repo: Path) -> int:
    cfg = load_config(repo)
    problems = [f"{rel}: {'missing' if old is None else 'differs from the config'} (render again)"
                for rel, old, new in changes(repo, cfg)]
    problems += findings(repo, cfg)
    for p in problems:
        print(f"- {p}")
    print("OK: the files match the config." if not problems else f"\n{len(problems)} finding(s).")
    return 1 if problems else 0


def findings(repo: Path, cfg: dict) -> list[str]:
    """Mistakes a config can hold that its syntax does not show."""
    out = []
    files = tracked_files(repo)
    if not cfg["checks"]:
        out.append("checks is empty: nothing tells a worker its change is wrong. "
                   "Make a test command the first issue.")
    if files:
        for g in cfg["critical_paths"]:
            if g not in DEFAULTS["critical_paths"] and not any(matches(g, f) for f in files):
                out.append(f"critical_paths: `{g}` matches no file")
        owners: dict[str, str] = {}
        for lane, globs in cfg["lanes"].items():
            hit = [f for f in files if any(matches(g, f) for g in globs)]
            if not hit:
                out.append(f"lane `{lane}` matches no file")
            for f in hit:
                if owners.setdefault(f, lane) != lane:
                    out.append(f"lanes `{owners[f]}` and `{lane}` both own {f}; lanes must not overlap")
                    break
    if cfg["lanes"] and cfg["parallel_workers"] == 1:
        out.append("lanes are set but parallel_workers is 1: lanes only matter with two or more workers")
    claude_md = repo / "CLAUDE.md"
    if claude_md.exists() and len(claude_md.read_text(encoding="utf-8").splitlines()) > 200:
        out.append("CLAUDE.md is over 200 lines: every session and subagent loads all of it; "
                   "move path-specific parts to .claude/rules/ with `paths:`")
    return out


def tracked_files(repo: Path) -> list[str]:
    try:
        res = subprocess.run(["git", "-C", str(repo), "ls-files"], capture_output=True, text=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        return []
    return res.stdout.splitlines()


def matches(glob: str, path: str) -> bool:
    rx = re.escape(glob).replace(r"\*\*/", "(?:.*/)?").replace(r"\*\*", ".*").replace(r"\*", "[^/]*").replace(r"\?", "[^/]")
    return re.fullmatch(rx, path) is not None


def cmd_detect(repo: Path) -> int:
    """Propose config values from what the repository already has."""
    has = lambda rel: (repo / rel).exists()  # noqa: E731
    text = lambda rel: (repo / rel).read_text(encoding="utf-8", errors="replace") if has(rel) else ""  # noqa: E731
    checks = []
    if has("pyproject.toml"):
        run = "uv run " if has("uv.lock") else ""
        if "[tool.ruff" in text("pyproject.toml") or has("ruff.toml"):
            checks.append(f"{run}ruff check")
        if has("tests") or "pytest" in text("pyproject.toml"):
            checks.append(f"{run}pytest")
    elif has("package.json"):
        try:
            scripts = json.loads(text("package.json")).get("scripts", {})
        except json.JSONDecodeError:
            scripts = {}
        checks += [f"npm run {s}" for s in ("lint", "typecheck") if s in scripts]
        checks += ["npm test"] if "test" in scripts else []
    elif has("Cargo.toml"):
        checks = ["cargo clippy", "cargo test"]
    elif has("go.mod"):
        checks = ["go vet ./...", "go test ./..."]
    elif re.search(r"^test:", text("Makefile"), re.M):
        checks = ["make test"]

    workflows = sorted((repo / ".github/workflows").glob("*.y*ml")) if has(".github/workflows") else []
    ci_on_prs = any("pull_request" in w.read_text(encoding="utf-8", errors="replace") for w in workflows)

    lanes = {}
    for base in [p for p in (repo / "src").glob("*") if (p / "__init__.py").exists()] + \
                [repo / d for d in ("packages", "apps", "crates") if has(d)]:
        subs = sorted(p for p in base.iterdir() if p.is_dir() and not p.name.startswith(("_", ".")))
        if len(subs) >= 2:
            lanes = {re.sub(r"[^a-z0-9]+", "-", p.name.lower()).strip("-"): [f"{p.relative_to(repo).as_posix()}/**"]
                     for p in subs}
            break

    branch = "main"
    try:
        ref = subprocess.run(["git", "-C", str(repo), "symbolic-ref", "--short", "refs/remotes/origin/HEAD"],
                             capture_output=True, text=True)
        if ref.returncode == 0 and ref.stdout.strip():
            branch = ref.stdout.strip().split("/", 1)[1]
    except OSError:
        pass

    licence = next((n for n in ("LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING") if has(n)), None)
    print(json.dumps({
        "proposed": {
            "name": repo.resolve().name,
            "size": "open-source" if licence and ci_on_prs else "solo",
            "default_branch": branch,
            "checks": " && ".join(checks),
        },
        "lane_candidates": lanes,
        "found": {
            "licence_file": licence,
            "ci_on_pull_requests": ci_on_prs,
            "config": has(CONFIG),
            "claude_md_lines": len(text("CLAUDE.md").splitlines()),
            "existing_agents": sorted(p.name for p in (repo / ".claude/agents").glob("*.md")) if has(".claude/agents") else [],
            "v1_governance": any(repo.glob("**/claude-project-rules.yaml")),
        },
    }, indent=2))
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["detect", "render", "check"])
    ap.add_argument("repo", type=Path)
    ap.add_argument("--dry-run", action="store_true", help="render: print the diff and write nothing")
    args = ap.parse_args(argv)
    if not args.repo.is_dir():
        print(f"error: {args.repo} is not a directory", file=sys.stderr)
        return 2
    try:
        if args.command == "detect":
            return cmd_detect(args.repo)
        if args.command == "render":
            return cmd_render(args.repo, args.dry_run)
        return cmd_check(args.repo)
    except ConfigError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
